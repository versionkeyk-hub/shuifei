// 根据成分名获取扩展信息（支持复配名查找）
function getPesticideExtra(componentName) {
  // 先精确匹配
  if (PESTICIDE_EXTRAS[componentName]) {
    return PESTICIDE_EXTRAS[componentName];
  }
  // 复配名拆分查找（如"戊唑醇・嘧菌酯"）
  var parts = componentName.split(/[·・]/).map(function(s) { return s.trim(); });
  if (parts.length > 1) {
    var phParts = [];
    var contraParts = [];
    parts.forEach(function(part) {
      if (PESTICIDE_EXTRAS[part]) {
        var ex = PESTICIDE_EXTRAS[part];
        if (phParts.indexOf(ex.ph) < 0) phParts.push(ex.ph);
        if (contraParts.indexOf(ex.contraindications) < 0) contraParts.push(ex.contraindications);
      }
    });
    if (phParts.length || contraParts.length) {
      return {
        ph: phParts.length ? phParts.join(' / ') : null,
        contraindications: contraParts.length ? contraParts.join('\n\n') : null
      };
    }
  }
  return null;
}
